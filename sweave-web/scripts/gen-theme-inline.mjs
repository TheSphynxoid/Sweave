// Generates the no-FOUC inline <script> in sweave-web/index.html.
//
// Source of truth stays in src/lib/theme/tokens.ts (+ fontScale.ts); this
// script compiles those two modules with the repo's own tsc, embeds a
// compact {mode, tokens} table + font-scale map into a self-contained
// pre-paint script, and splices it between the SWEAVE-THEME-INLINE
// markers in index.html.
//
// Re-run after ANY change to tokens.ts / fontScale.ts / theme storage
// keys:
//   cd sweave-web && node scripts/gen-theme-inline.mjs
// A vitest (`src/lib/theme/__tests__/inline.test.ts`) pins the embedded
// table against the live modules, so a stale inline block fails the gate.

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";
import Module from "node:module";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);

const START = "<!-- SWEAVE-THEME-INLINE:START -->";
const END = "<!-- SWEAVE-THEME-INLINE:END -->";

// Theme storage keys mirror the private consts in
// src/lib/theme/switcher.ts (STORAGE_KEY_PRESET / STORAGE_KEY_CUSTOM).
// They are intentionally stable strings; setup.ts hardcodes them too.
const THEME_PRESET_KEY = "sweave.theme.preset";
const THEME_CUSTOM_KEY = "sweave.theme.custom";

function findFile(dir, name) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isFile() && entry.name === name) return full;
    if (entry.isDirectory()) {
      const hit = findFile(full, name);
      if (hit) return hit;
    }
  }
  return null;
}

// Outside the repo (package.json says "type": "module", so compiled
// CommonJS must not live under sweave-web/ or node treats it as ESM).
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "sweave-theme-inline-"));
try {
  // Use the repo's own tsc directly (npx.cmd spawn is unreliable here).
  const tsc = path.join(root, "node_modules", "typescript", "bin", "tsc");
  execFileSync(
    process.execPath,
    [
      tsc,
      "src/lib/theme/tokens.ts",
      "src/lib/theme/fontScale.ts",
      "--outDir",
      tmp,
      "--module",
      "commonjs",
      "--target",
      "es2020",
      "--skipLibCheck",
      "--jsx",
      "react-jsx",
    ],
    { cwd: root, stdio: "inherit" },
  );

  const tokensPath = findFile(tmp, "tokens.js");
  const fontScalePath = findFile(tmp, "fontScale.js");
  if (!tokensPath || !fontScalePath) throw new Error("compiled modules not found");

  // The compiled fontScale.js requires react (jsx runtime); the tmp dir
  // lives outside the package, so point CJS resolution at our node_modules.
  process.env.NODE_PATH = path.join(root, "node_modules");
  Module._initPaths();

  const tokens = require(tokensPath);
  const fontScale = require(fontScalePath);

  const table = {};
  for (const p of tokens.PRESETS) table[p.name] = { mode: p.mode, tokens: { ...p.tokens } };
  const scales = {};
  for (const o of fontScale.FONT_SCALE_OPTIONS) scales[o.id] = o.multiplier;

  const script =
    "<script>\n" +
    "/* GENERATED by scripts/gen-theme-inline.mjs -- do not hand-edit. Rerun\n" +
    " * `node scripts/gen-theme-inline.mjs` after touching tokens.ts /\n" +
    " * fontScale.ts. Mirrors applyThemeToDocument + applyFontScale for the\n" +
    " * very first paint (ASCII only; never contains a closing script tag). */\n" +
    "(function(){try{\n" +
    "var PRESETS=" +
    JSON.stringify(table) +
    ";\n" +
    'var DEFAULT_DARK="' +
    tokens.DEFAULT_PRESET_NAME +
    '",DEFAULT_LIGHT="' +
    tokens.DEFAULT_LIGHT_PRESET_NAME +
    '";\n' +
    "var SCALES=" +
    JSON.stringify(scales) +
    ',DEFAULT_SCALE="' +
    fontScale.DEFAULT_FONT_SCALE_ID +
    '";\n' +
    'var THEME_PRESET_KEY="' +
    THEME_PRESET_KEY +
    '",THEME_CUSTOM_KEY="' +
    THEME_CUSTOM_KEY +
    '",FONT_SCALE_KEY="' +
    fontScale.FONT_SCALE_STORAGE_KEY +
    '";\n' +
    "function ls(k){try{return window.localStorage.getItem(k)}catch(e){return null}}\n" +
    "var preset=ls(THEME_PRESET_KEY)||DEFAULT_DARK;\n" +
    "var custom={};try{var raw=JSON.parse(ls(THEME_CUSTOM_KEY)||\"{}\");" +
    'if(raw&&typeof raw==="object"&&!Array.isArray(raw))custom=raw}catch(e){custom={}}\n' +
    'var mq=(typeof window.matchMedia==="function")' +
    '?window.matchMedia("(prefers-color-scheme: dark)"):null;\n' +
    "var darkOS=!mq||mq.matches;\n" +
    'var eff=(preset==="system")?(darkOS?DEFAULT_DARK:DEFAULT_LIGHT):preset;\n' +
    "var entry=PRESETS[eff]||PRESETS[DEFAULT_DARK];\n" +
    "var root=document.documentElement;\n" +
    'root.setAttribute("data-theme",preset);\n' +
    'var css=":root[data-theme=\\""+preset+"\\"]{";\n' +
    "for(var k in entry.tokens){" +
    'var v=(typeof custom[k]==="string"&&custom[k])||entry.tokens[k];' +
    'css+="--color-"+k+":rgb("+v+");"}\n' +
    'css+="}";\n' +
    'if(entry.mode==="dark")root.classList.add("dark");else root.classList.remove("dark");\n' +
    "try{root.style.colorScheme=entry.mode}catch(e){}\n" +
    'var el=document.getElementById("sweave-theme-vars");\n' +
    'if(!el){el=document.createElement("style");el.id="sweave-theme-vars";' +
    "document.head.appendChild(el);}\n" +
    "el.textContent=css;\n" +
    "var fs=ls(FONT_SCALE_KEY);\n" +
    "if(!SCALES[fs])fs=DEFAULT_SCALE;\n" +
    'try{root.style.setProperty("--sweave-root-scale",String(SCALES[fs]))}catch(e){}\n' +
    "}catch(e){}})();\n" +
    "</script>";

  const htmlPath = path.join(root, "index.html");
  const html = fs.readFileSync(htmlPath, "utf8");
  const block = START + "\n" + script + "\n" + END;
  // A literal closing script tag inside the block would end the element
  // early and leak the remaining JS as visible page text. Fail loudly.
  if (/<\/script/i.test(script.replace(/<script>/, "").replace(/<\/script>$/, ""))) {
    throw new Error("inline script body contains a closing script tag");
  }
  let next;
  const si = html.indexOf(START);
  const ei = html.indexOf(END);
  if (si !== -1 && ei !== -1 && ei > si) {
    next = html.slice(0, si) + block + html.slice(ei + END.length);
  } else if (html.includes("</head>")) {
    const indented = block
      .split("\n")
      .map((line) => (line ? "  " + line : line))
      .join("\n");
    next = html.replace("</head>", indented + "\n  </head>");
  } else {
    throw new Error("index.html has no </head>");
  }
  fs.writeFileSync(htmlPath, next);
  console.log("index.html inline theme script updated (" + Object.keys(table).length + " presets).");
} finally {
  fs.rmSync(tmp, { recursive: true, force: true });
}
